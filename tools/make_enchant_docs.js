// Writes docs/ENCHANTS.md from the config and tome recipes, so the docs never drift.
// Usage (from repo root):  java -jar rhino-1.7.15.jar -version 200 tools/make_enchant_docs.js
var global = {}
var console = { info: function () {}, error: function (m) { print(m) } }
var recipes = {}
var ServerEvents = {
  recipes: function (fn) {
    fn({ custom: function (j) { if (/tome_/.test(j.results[0].item)) recipes[j.results[0].item.replace('kubejs:tome_', '')] = j.ingredients.map(function (i) { return i.item }).filter(function (i) { return i != 'kubejs:blank_ascension_tome' }); return { id: function () {} } } })
  }
}
load('kubejs/startup_scripts/00_fa_config.js')
load('kubejs/server_scripts/25_fa_tome_recipes.js')

var groups = [
  ['Damage', ['damage', 'critical', 'reaper', 'cleave']],
  ['On hit', ['lifesteal', 'hit_effect', 'ignite', 'hit_heal', 'self_effect']],
  ['On kill', ['plunder', 'kill_heal', 'xp', 'drop']],
  ['Defense', ['resist', 'vitality', 'retribution', 'dodge', 'undying']],
  ['Passive', ['regen', 'passive', 'magnet', 'repair']],
  ['Movement & utility', ['attribute', 'mining', 'eternal']],
  ['Mythic', 'mythic'],
  ['Ultimate', 'ultimate'],
  ['Fusion', 'fusion']
]
function nice(id) {
  if (id.indexOf('kubejs:tome_') === 0 && global.FA.enchants[id.slice(12)]) return 'Tome of ' + global.FA.enchants[id.slice(12)].name
  return id.replace(/^(minecraft|create|kubejs):/, '').replace(/_/g, ' ')
}
function catalysts(id) {
  var counts = {}, order = []
  recipes[id].filter(function (i) { return i != 'kubejs:mythic_fragment' && i != 'kubejs:ascended_soul' }).forEach(function (i) { if (!counts[i]) { counts[i] = 0; order.push(i) } counts[i]++ })
  return order.map(function (i) { return (counts[i] > 1 ? counts[i] + 'x ' : '') + nice(i) }).join(', ')
}

var E = global.FA.enchants
var out = ['# Ascended enchants', '',
  Object.keys(E).length + ' enchants. Levels have no cap unless a max is listed. Each enchant counts from every equipped item',
  '(both hands and all armor), so any enchant works on any gear.', '',
  'Unlock: hold a Tome in one hand and the gear in the other, right-click the tome.',
  'Upgrade: hold the gear, type `/ascension`, click the buttons.', '',
  'Every tome is made in a **heated mixer**: Blank Ascension Tome + the catalysts below.', '',
  '_Generated by `tools/make_enchant_docs.js` from `00_fa_config.js`._', '']
groups.forEach(function (g) {
  out.push('## ' + g[0], '')
  if (g[1] == 'mythic') {
    out.push('Rare and crazy. Mythic tomes need **4 Mythic Fragments** + a catalyst in a **superheated** mixer.',
      'Fragments only drop from mobs out in the danger zones killed by a player: Elites drop them often',
      '(15% + 0.5% per danger level, max 75%), other danger-zone mobs rarely (0.2% per danger level, max 5%).',
      'Mythic levels cost ' + global.FA.mythicCostMultiplier + 'x the Essence.', '')
  }
  if (g[1] == 'ultimate') {
    out.push('Cinematic combo moves: **sneak + hit** an enemy to unleash one. You can\'t be hurt mid-combo and always land back where you started.',
      'Every strike deals the triggering hit\'s damage x the power below, so your other enchants make them stronger. Each level adds 25% power and',
      'takes 1 second off the cooldown (5 s minimum). Tomes need **2 Ascended Souls** (only Ascended bosses drop them) + 4 Mythic Fragments, superheated.',
      'Ultimate levels cost ' + global.FA.ultimateCostMultiplier + 'x the Essence.', '')
  }
  if (g[1] == 'fusion') {
    out.push('Two enchants fused into one tome: each Fusion does both of its parents\' effects at ' + Math.round(global.FA.fusionStrength * 100) + '% strength.',
      'Tome: the two parent tomes + an Ascension Core in a **heated** mixer. Fusion levels cost ' + global.FA.fusionCostMultiplier + 'x the Essence.', '')
  }
  out.push('| Enchant | Level 1 | Level 100 | Max | Tome catalysts |', '|---|---|---|---|---|')
  Object.keys(E).forEach(function (id) {
    var e = E[id]
    if (g[1] == 'mythic' ? !e.mythic : g[1] == 'ultimate' ? !e.ultimate : g[1] == 'fusion' ? e.type != 'fusion' : (e.mythic || e.ultimate || e.type == 'fusion' || g[1].indexOf(e.type) < 0)) return
    var at100 = e.maxLevel ? '' : global.FA_describe(id, 100)
    out.push('| **' + e.name + '** | ' + global.FA_describe(id, 1) + ' | ' + at100 + ' | ' +
      (e.maxLevel ? e.maxLevel + ' (' + global.FA_describe(id, e.maxLevel) + ')' : 'none') + ' | ' + catalysts(id) + ' |')
  })
  out.push('')
})
var w = new java.io.FileWriter('docs/ENCHANTS.md')
w.write(out.join('\n'))
w.close()
print('wrote docs/ENCHANTS.md (' + Object.keys(E).length + ' enchants)')
